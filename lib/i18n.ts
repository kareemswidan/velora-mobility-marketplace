export const dictionaries = { en, ar } as const;

export function translator(locale: Locale) {
  const table = locale === "ar" ? ar : en;
  return (key: Key): string => table[key] ?? en[key];
}

export function normalizeLocale(value: string | undefined | null): Locale {
  return value === "ar" ? "ar" : "en";
}

/** Pick the Arabic column when the page is Arabic and the row actually has one.
 *  Keeps the English value as the fallback so partly-translated rows still read. */
export function localized<T extends Record<string, any>>(locale: Locale, row: T | null | undefined, field: string): string {
  if (!row) return "";
  if (locale === "ar") {
    const v = row[`${field}Ar`];
    if (typeof v === "string" && v.trim()) return v;
  }
  return String(row[field] ?? "");
}

