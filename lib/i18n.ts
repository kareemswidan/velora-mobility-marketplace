/** BCP-47 tag for Intl. Arabic keeps Latin digits, which is what Gulf and
 *  Levant users expect on the web even when the copy is Arabic. */
export function intlLocale(locale: Locale): string {
  return locale === "ar" ? "ar-u-nu-latn" : "en-US";
}
